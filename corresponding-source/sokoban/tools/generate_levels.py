#!/usr/bin/env python3
"""Rebuild embedded original puzzles; --check verifies byte-for-byte parity.

Flood-fill only boundary-connected spaces to distinguish exterior void from
walkable floor. Puzzle coordinates and interior spaces are never shifted.
"""
import argparse
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def normalize_level(lines):
    """Return rectangular rows with '-' exterior, plus original dimensions."""
    width, height = max(map(len, lines)), len(lines)
    if not (1 <= width <= 19 and 1 <= height <= 16):
        raise ValueError(f"Unsupported puzzle dimensions {width}x{height}")
    if any(c not in ' #.$*@+' for row in lines for c in row):
        raise ValueError('Unknown level symbol')
    if sum(c in '@+' for row in lines for c in row) != 1:
        raise ValueError('Expected exactly one keeper')
    boxes = sum(c in '$*' for row in lines for c in row)
    goals = sum(c in '.*+' for row in lines for c in row)
    if not 1 <= boxes == goals <= 34:
        raise ValueError('Box/goal counts must match and be in 1..34')
    grid = [list(' ' * (width + 2))]
    grid += [list(' ' + row.ljust(width) + ' ') for row in lines]
    grid += [list(' ' * (width + 2))]
    todo, outside = deque([(0, 0)]), {(0, 0)}
    while todo:
        x, y = todo.popleft()
        for nx, ny in ((x-1, y), (x+1, y), (x, y-1), (x, y+1)):
            if (0 <= nx < width+2 and 0 <= ny < height+2
                    and (nx, ny) not in outside and grid[ny][nx] == ' '):
                outside.add((nx, ny))
                todo.append((nx, ny))
    rows = [''.join('-' if (x+1, y+1) in outside else grid[y+1][x+1]
                    for x in range(width)) for y in range(height)]
    return rows, width, height


def generate():
    out = ['/** GENERATED by tools/generate_levels.py; do not hand-edit.',
           ' * Original puzzles supplied with pySokoban; see ATTRIBUTION.md.',
           ' * Board.load clears state. Each row string transfers ownership to Board.',
           ' * Fixed stride 20; exterior spaces encoded as void, never walkable.',
           ' */', 'class Levels {',
           '    function void load(Board board, int level) {']
    for bucket in range(5):
        out += [f'        if ((level > {bucket*10}) & (level < {bucket*10+11})) {{',
                f'            do Levels.load{bucket+1}(board, level);',
                '            return;', '        }']
    out += ['        return;', '    }']
    for bucket in range(5):
        out += [f'    function void load{bucket+1}(Board board, int level) {{']
        for number in range(bucket*10+1, bucket*10+11):
            rows, width, height = normalize_level(
                (ROOT / 'levels' / 'original' / f'level{number}').read_text().splitlines())
            out += [f'        // Puzzle {number}: {width} columns, {height} rows.',
                    f'        if (level = {number}) {{',
                    f'            do board.setSize({width}, {height});']
            out += [f'            do board.row("{row}", {y});' for y, row in enumerate(rows)]
            out += ['            return;', '        }']
        out += ['        return;', '    }']
    return '\n'.join(out + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, target = generate(), ROOT / 'Levels.jack'
    if args.check:
        if not target.exists() or target.read_text() != content:
            parser.exit(1, 'Levels.jack is stale; run tools/generate_levels.py\n')
        print('All 50 levels validated; Levels.jack matches')
    else:
        target.write_text(content)
        print('Generated Levels.jack: 50 levels, at most 19x16')


if __name__ == '__main__':
    main()
